// Dates relative to today in the firm's time zone (Mountain), so the calendar's "upcoming" rules are tested as they run.
const today = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Denver", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
const plus = (days: number) => new Date(Date.parse(`${today}T00:00:00Z`) + days * 86_400_000).toISOString().slice(0, 10);
const us = (iso: string) => { const [y, m, d] = iso.split("-").map(Number); return `${m}/${d}/${y}`; };

const notice = (o: { entered: string; hearing: string; due: string; caseNo?: string }) => [
  "From: cmecf_notice@utd.uscourts.gov", "To: Jane Smith <jane@firm.example>",
  `Subject: Activity in Case ${o.caseNo ?? "2:26-cv-00123-DBB"} Smith v. Acme Corporation Order on Motion to Dismiss`,
  "Date: Mon, 02 Nov 2026 15:14:00 -0700", "MIME-Version: 1.0", "Content-Type: text/plain", "",
  "This is an automatic e-mail message generated by the CM/ECF system. Please DO NOT RESPOND to this e-mail because the mail box is unattended.",
  "", "U.S. District Court", "", "District of Utah", "", "Notice of Electronic Filing", "",
  `The following transaction was entered on ${us(o.entered)} at 3:14 PM MST and filed on ${us(o.entered)}`,
  "Case Name: Smith v. Acme Corporation", `Case Number: ${o.caseNo ?? "2:26-cv-00123-DBB"}`, "Filer:", "Document Number: 12", "",
  "Docket Text:",
  `ORDER granting in part [10] Motion to Dismiss. Motion Hearing set for ${us(o.hearing)} at 10:00 AM in Room 7.100 before Judge David Barlow. Responses due by ${us(o.due)}. Signed by Judge David Barlow. (jds)`,
  "", "", "2:26-cv-00123-DBB Notice has been electronically mailed to:", "Jane Smith  jane@firm.example", "",
  "https://ecf.utd.uscourts.gov/doc1/18315123456?caseid=139421&de_seq_num=55&magic_num=12345", "",
].join("\r\n");

async function setup() {
  const f = await newFirm(db);
  const x = await db.withFirm(f.owner, async (s) => {
    const client = await createClient(s, { kind: "person", displayName: "Pat Smith", email: "pat.smith@example.com" });
    const para = await inviteUser(s, { email: `p@${f.slug}.example`, fullName: "Pat Para", role: "paralegal", locationId: f.locationId });
    const reader = await inviteUser(s, { email: `r@${f.slug}.example`, fullName: "Rae Reader", role: "read_only", locationId: f.locationId });
    const portal = await inviteUser(s, { email: `c@${f.slug}.example`, fullName: "Casey Client", role: "client", locationId: f.locationId });
    const matter = await createMatter(s, { title: "Smith v. Acme", clientId: client.id, leadAttorneyId: f.ownerUserId, jurisdictionState: "UT" });
    const other = await createMatter(s, { title: "Other", clientId: client.id, leadAttorneyId: f.ownerUserId, jurisdictionState: "UT" });
    const walled = await createMatter(s, { title: "Walled", clientId: client.id, leadAttorneyId: f.ownerUserId, jurisdictionState: "UT", restricted: true });
    await setCourtCaseNumber(s, matter.id, "2:26-cv-00123");
    return { para, reader, portal, matter, other, walled };
  });
  await db.withFirm(f.owner, (s) => addMatterMember(s, { matterId: x.matter.id, userId: x.portal.id, access: "view", acknowledgePrivilegeWaiverRisk: true }));
  const ctx = (id: string): RequestContext => ({ firmId: f.firmId, userId: id });
  return { ...f, ...x, paraCtx: ctx(x.para.id), readerCtx: ctx(x.reader.id), portalCtx: ctx(x.portal.id) };
}

describe("reading federal court notices", () => {
  it("reads the court, case, document, docket text and the dates it sets, by fixed rules", () => {
    const text = notice({ entered: "2026-04-18", hearing: "2026-05-20", due: "2026-05-04" });
    const n = parseNef(text)!;
    expect(n).toMatchObject({
      court: "U.S. District Court, District of Utah", caseNumber: "2:26-cv-00123-DBB", caseName: "Smith v. Acme Corporation",
      documentNumber: "12", enteredOn: "2026-04-18",
      documentUrl: "https://ecf.utd.uscourts.gov/doc1/18315123456?caseid=139421&de_seq_num=55&magic_num=12345",
    });
    expect(n.docketText).toMatch(/^ORDER granting in part/);
    expect(n.events.map((e) => [e.kind, e.title, e.date, e.time, e.location, e.judge])).toEqual([
      ["hearing", "Motion Hearing", "2026-05-20", "10:00", "Room 7.100", "Judge David Barlow"],
      ["deadline", "Responses due", "2026-05-04", null, null, null],
    ]);
    // Each date keeps the exact words it came from.
    expect(text.slice(n.events[1]!.start, n.events[1]!.end)).toBe("Responses due by 5/4/2026");
  });

  it("recognizes only court notices, skips impossible dates, and stays bounded on hostile text", () => {
    expect(isNef("Hi Pat, the hearing is set for 5/20/2026.")).toBe(false);
    expect(parseNef("Lunch set for 5/20/2026 at noon.")).toBeNull();
    expect(usDate("2", "30", "2026")).toBeNull();
    expect(usDate("4", "1", "26")).toBe("2026-04-01");
    expect(clock("2:30 PM")).toBe("14:30");
    expect(clock("12:15 a.m.")).toBe("00:15");
    expect(clock("13:00 PM")).toBeNull();
    const bad = notice({ entered: "2026-04-18", hearing: "2026-02-30", due: "2026-13-01" });
    expect(parseNef(bad)!.events).toEqual([]);
    const started = Date.now();
    const hostile = `Notice of Electronic Filing CM/ECF\nDocket Text:\n${"Motion Hearing set for 1/1/2026 at ".repeat(20_000)}${"A".repeat(200_000)}`;
    expect(parseNef(hostile)!.events.length).toBeLessThanOrEqual(20);
    expect(Date.now() - started).toBeLessThan(2000);
  });

  it("names reminders on the standard 30/14/7/3/1-day schedule", () => {
    expect([30, 14, 7, 3, 1, 0, -1, 10].map(alertFor)).toEqual(["In 30 days", "In 14 days", "In 7 days", "In 3 days", "Tomorrow", "Today", "Past", null]);
  });
});

describe("court calendar", () => {
  it("proposes dates from a court notice filed into the Matter; nothing counts until an attorney confirms it", async () => {
    const x = await setup();
    const nef = await upload(x.owner, x.matter.id, "nef.eml", notice({ entered: plus(-3), hearing: plus(7), due: plus(14) }));
    await process();
    let events = await db.withFirm(x.paraCtx, (s) => listCourtEvents(s, x.matter.id));
    expect(events.map((e) => [e.status, e.origin, e.kind, e.title, e.date, e.time])).toEqual([
      ["suggested", "huis", "hearing", "Motion Hearing", plus(7), "10:00"],
      ["suggested", "huis", "deadline", "Responses due", plus(14), null],
    ]);
    expect(events[0]).toMatchObject({ sourceEvidenceId: nef.id, sourceTitle: "nef.eml", daysAway: 7 });
    expect(events[0]!.quote).toContain("Motion Hearing set for");
    // Proposals never reach the dashboard.
    expect(await db.withFirm(x.paraCtx, (s) => upcomingCourtDates(s))).toEqual([]);

    // The docket, read from the notice, with the free look still open.
    const docket = await db.withFirm(x.paraCtx, (s) => courtNotices(s, x.matter.id));
    expect(docket).toHaveLength(1);
    expect(docket[0]).toMatchObject({ evidenceId: nef.id, caseNumber: "2:26-cv-00123-DBB", documentNumber: "12", datesFound: 2, freeLookDaysLeft: 12, caseMismatch: false });

    // Confirm the hearing, reject the deadline.
    await db.withFirm(x.owner, (s) => decideCourtEvent(s, events[0]!.id, "confirmed"));
    await db.withFirm(x.owner, (s) => decideCourtEvent(s, events[1]!.id, "rejected"));
    const up = await db.withFirm(x.paraCtx, (s) => upcomingCourtDates(s));
    expect(up.map((u) => [u.title, u.matterTitle, u.alert])).toEqual([["Motion Hearing", "Smith v. Acme", "In 7 days"]]);
    // Who decided and when is recorded by the database.
    const decided = (await t.admin.query("SELECT decided_by, decided_at FROM huis.court_events WHERE id = $1", [events[0]!.id])).rows[0];
    expect(decided.decided_by).toBe(x.ownerUserId);
    expect(decided.decided_at).toBeTruthy();

    // Reading the notice again doesn't propose the rejected date again or duplicate the hearing.
    await t.admin.query("UPDATE huis.brain_sources SET status = 'queued' WHERE evidence_id = $1", [nef.id]);
    await process();
    events = await db.withFirm(x.paraCtx, (s) => listCourtEvents(s, x.matter.id, { includeRejected: true }));
    expect(events.map((e) => e.status).sort()).toEqual(["confirmed", "rejected"]);

    // Done, then reopened; the database records who.
    await db.withFirm(x.paraCtx, (s) => setCourtEventDone(s, events.find((e) => e.status === "confirmed")!.id, true));
    expect(await db.withFirm(x.paraCtx, (s) => upcomingCourtDates(s))).toEqual([]);
    expect((await t.admin.query("SELECT done_by FROM huis.court_events WHERE status = 'confirmed' AND matter_id = $1", [x.matter.id])).rows[0].done_by).toBe(x.para.id);
    await db.withFirm(x.paraCtx, (s) => setCourtEventDone(s, events.find((e) => e.status === "confirmed")!.id, false));
    expect(await db.withFirm(x.paraCtx, (s) => upcomingCourtDates(s))).toHaveLength(1);

    // A notice for a different case is flagged.
    await upload(x.owner, x.matter.id, "other-case.eml", notice({ entered: plus(-1), hearing: plus(20), due: plus(25), caseNo: "2:25-cv-00999-XYZ" }));
    await process();
    expect((await db.withFirm(x.paraCtx, (s) => courtNotices(s, x.matter.id))).find((n) => n.caseNumber === "2:25-cv-00999-XYZ")!.caseMismatch).toBe(true);
  });

  it("Huis's proposals can't be planted, changed before confirming, or deleted — even directly in the database", async () => {
    const x = await setup();
    const nef = await upload(x.owner, x.matter.id, "nef.eml", notice({ entered: plus(-3), hearing: plus(7), due: plus(14) }));
    await process();
    const [hearing] = await db.withFirm(x.owner, (s) => listCourtEvents(s, x.matter.id));
    await expect(db.withFirm(x.owner, (s) => updateCourtEvent(s, hearing!.id, { kind: "hearing", title: "x", date: plus(8) }))).rejects.toThrow(/Confirm/);
    await expect(db.withFirm(x.owner, (s) => s.client.query("UPDATE huis.court_events SET event_date = $2 WHERE id = $1", [hearing!.id, plus(30)]))).rejects.toThrow(/Confirm a proposed/);
    await expect(db.withFirm(x.owner, (s) => deleteCourtEvent(s, hearing!.id))).rejects.toThrow(/reject them instead/);
    expect((await db.withFirm(x.owner, (s) => s.client.query("DELETE FROM huis.court_events WHERE id = $1", [hearing!.id]))).rowCount).toBe(0);
    // Nobody can plant a "Huis" proposal, a fake quote, or one in someone else's name.
    await expect(db.withFirm(x.owner, (s) => s.client.query(
      `INSERT INTO huis.court_events (firm_id, matter_id, kind, title, event_date, status, origin, source_evidence_id, char_start, char_end, quote)
       VALUES ($1, $2, 'deadline', 'Fake', $3, 'suggested', 'huis', $4, 0, 5, 'fake')`, [x.firmId, x.matter.id, plus(2), nef.id]))).rejects.toThrow();
    await expect(db.withFirm(x.owner, (s) => s.client.query(
      `INSERT INTO huis.court_events (firm_id, matter_id, kind, title, event_date, status, origin, created_by)
       VALUES ($1, $2, 'deadline', 'Fake', $3, 'confirmed', 'attorney', $4)`, [x.firmId, x.matter.id, plus(2), x.para.id]))).rejects.toThrow();
    // History can't be rewritten after confirming either.
    await db.withFirm(x.owner, (s) => decideCourtEvent(s, hearing!.id, "confirmed"));
    await expect(db.withFirm(x.owner, (s) => s.client.query("UPDATE huis.court_events SET quote = 'changed' WHERE id = $1", [hearing!.id]))).rejects.toThrow(/history/);
    await expect(db.withFirm(x.owner, (s) => s.client.query("UPDATE huis.court_events SET decided_by = NULL WHERE id = $1", [hearing!.id]))).rejects.toThrow(/history/);
    await expect(db.withFirm(x.owner, (s) => s.client.query("UPDATE huis.court_events SET status = 'suggested' WHERE id = $1", [hearing!.id]))).rejects.toThrow();
    // Once confirmed, an attorney can correct it.
    await db.withFirm(x.owner, (s) => updateCourtEvent(s, hearing!.id, { kind: "hearing", title: "Motion Hearing (moved)", date: plus(9), time: "13:30" }));
    expect((await db.withFirm(x.owner, (s) => listCourtEvents(s, x.matter.id)))[0]).toMatchObject({ title: "Motion Hearing (moved)", date: plus(9), time: "13:30" });
  });

  it("only firm staff on the Matter see it; read-only staff can't change it; clients, walls, other Matters and firms are kept out", async () => {
    const x = await setup();
    const id = await db.withFirm(x.paraCtx, (s) => addCourtEvent(s, x.matter.id, { kind: "deadline", title: "Expert disclosures", date: plus(3) }));
    const walledId = await db.withFirm(x.owner, (s) => addCourtEvent(s, x.walled.id, { kind: "hearing", title: "Secret hearing", date: plus(3) }));

    expect((await db.withFirm(x.readerCtx, (s) => listCourtEvents(s, x.matter.id))).map((e) => e.title)).toEqual(["Expert disclosures"]);
    await expect(db.withFirm(x.readerCtx, (s) => addCourtEvent(s, x.matter.id, { kind: "deadline", title: "x", date: plus(1) }))).rejects.toThrow(/permission/i);
    expect((await db.withFirm(x.readerCtx, (s) => s.client.query("UPDATE huis.court_events SET title = 'x'"))).rowCount).toBe(0);
    expect((await db.withFirm(x.readerCtx, (s) => s.client.query("DELETE FROM huis.court_events"))).rowCount).toBe(0);

    await expect(db.withFirm(x.portalCtx, (s) => listCourtEvents(s, x.matter.id))).rejects.toThrow(/permission/i);
    await expect(db.withFirm(x.portalCtx, (s) => courtCalendarIcs(s, x.matter.id, true))).rejects.toThrow(/permission/i);
    expect(await db.withFirm(x.portalCtx, (s) => upcomingCourtDates(s))).toEqual([]);
    expect((await db.withFirm(x.portalCtx, (s) => s.client.query("SELECT * FROM huis.court_events"))).rowCount).toBe(0);

    // Walls: the paralegal (outside the wall) never sees the walled Matter's dates, even on the dashboard.
    await expect(db.withFirm(x.paraCtx, (s) => listCourtEvents(s, x.walled.id))).rejects.toThrow(/not found/i);
    expect((await db.withFirm(x.paraCtx, (s) => upcomingCourtDates(s))).map((u) => u.title)).toEqual(["Expert disclosures"]);
    expect((await db.withFirm(x.owner, (s) => upcomingCourtDates(s))).map((u) => u.title).sort()).toEqual(["Expert disclosures", "Secret hearing"]);
    await expect(db.withFirm(x.paraCtx, (s) => decideCourtEvent(s, walledId, "rejected"))).rejects.toThrow(/not found/i);
    await expect(db.withFirm(x.paraCtx, (s) => s.client.query(
      `INSERT INTO huis.court_events (firm_id, matter_id, kind, title, event_date, status, origin, created_by)
       VALUES ($1, $2, 'deadline', 'Planted', $3, 'confirmed', 'attorney', $4)`, [x.firmId, x.walled.id, plus(2), x.para.id]))).rejects.toThrow();
    // Can't be moved to another Matter.
    await expect(db.withFirm(x.owner, (s) => s.client.query("UPDATE huis.court_events SET matter_id = $2 WHERE id = $1", [id, x.other.id]))).rejects.toThrow();

    const g = await newFirm(db, "Other Owner");
    expect((await db.withFirm(g.owner, (s) => s.client.query("SELECT * FROM huis.court_events"))).rowCount).toBe(0);
    expect(await db.withFirm(g.owner, (s) => upcomingCourtDates(s))).toEqual([]);
  });

  it("a notice found infected takes its proposed and confirmed dates with it", async () => {
    const x = await setup();
    const nef = await upload(x.owner, x.matter.id, "nef.eml", notice({ entered: plus(-3), hearing: plus(7), due: plus(14) }));
    await process();
    const [hearing] = await db.withFirm(x.owner, (s) => listCourtEvents(s, x.matter.id));
    await db.withFirm(x.owner, (s) => decideCourtEvent(s, hearing!.id, "confirmed"));
    await infect(nef.id);
    expect(await db.withFirm(x.owner, (s) => listCourtEvents(s, x.matter.id))).toEqual([]);
    expect(await db.withFirm(x.owner, (s) => upcomingCourtDates(s))).toEqual([]);
    expect(await db.withFirm(x.owner, (s) => courtNotices(s, x.matter.id))).toEqual([]);
  });

  it("exports confirmed dates as a calendar file that can't be broken by their wording; logs never hold wording", async () => {
    const x = await setup();
    await db.withFirm(x.owner, (s) => addCourtEvent(s, x.matter.id, {
      kind: "hearing", title: "Hearing; secret-word, part\r\nBEGIN:VEVENT", date: plus(5), time: "09:30", location: "Room 7", judge: "Judge Barlow", notes: "Bring exhibits",
    }));
    await db.withFirm(x.owner, (s) => addCourtEvent(s, x.matter.id, { kind: "deadline", title: "Responses due", date: plus(10) }));
    const { filename, body } = await db.withFirm(x.paraCtx, (s) => courtCalendarIcs(s, x.matter.id, true));
    expect(filename).toMatch(/-court-dates\.ics$/);
    // Like every export, only with the confirmation that it will be stored securely.
    await expect(db.withFirm(x.paraCtx, (s) => courtCalendarIcs(s, x.matter.id, false))).rejects.toThrow(/store the calendar file securely/);
    expect(body.match(/^BEGIN:VEVENT\r$/gm)).toHaveLength(2);
    expect(body).toContain("DTSTART;TZID=America/Denver:");
    expect(body).toContain(`DTSTART;VALUE=DATE:${plus(10).replace(/-/g, "")}`);
    expect(body).toContain("TRIGGER:-P7D");
    expect(icsText("a;b,c\\d\ne")).toBe("a\\;b\\,c\\\\d\\ne");
    for (const line of body.split("\r\n")) expect(Buffer.byteLength(line)).toBeLessThanOrEqual(75);

    const audit = await t.admin.query("SELECT action, metadata::text AS m FROM huis.audit_events WHERE firm_id = $1 AND action LIKE 'court.%'", [x.firmId]);
    expect(audit.rows.map((r) => r.action)).toEqual(expect.arrayContaining(["court.added", "court.calendar_exported"]));
    for (const r of audit.rows) expect(r.m).not.toMatch(/secret-word|Bring exhibits|Barlow/);
  });
});
