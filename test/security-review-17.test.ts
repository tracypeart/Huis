const scanner: MalwareScanner = {
  name: "test",
  async scan(stream) { for await (const _ of stream) { /* drain */ } return { status: "clean", detail: "No threats found" }; },
};

beforeAll(async () => {
  t = await createTestDatabase();
  db = t.db;
  vaultDir = await mkdtemp(path.join(os.tmpdir(), "huis-sr17-vault-"));
  vault = new EvidenceVault(new LocalObjectStore(vaultDir), new MasterKeyProvider(randomBytes(32).toString("base64")));
  processor = new EvidenceProcessor(t.worker, vault, scanner);
  brain = new BrainWorker(t.worker);
});
afterAll(async () => {
  await t?.drop();
  if (vaultDir) await rm(vaultDir, { recursive: true, force: true });
});

async function upload(ctx: RequestContext, matterId: string, filename: string, text: string) {
  const content = Buffer.from(text);
  const session = await db.withFirm(ctx, (s) => startUpload(s, { matterId, filename, totalSize: content.length }));
  for (let i = 0; i < session.chunkCount; i++) {
    await storeChunk(vault, session, i, content.subarray(i * session.chunkSize, (i + 1) * session.chunkSize));
    await db.withFirm(ctx, (s) => markChunkReceived(s, session.id, i));
  }
  const fresh = await db.withFirm(ctx, (s) => getUploadSession(s, session.id));
  const id = newEvidenceId();
  const stored = await assembleOriginal(vault, fresh, id);
  return db.withFirm(ctx, (s) => recordEvidence(s, fresh, id, stored));
}
async function process() {
  await processor.drain();
  while (await brain.indexOnce()) { /* index */ }
}

const today = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Denver", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
const plus = (days: number) => new Date(Date.parse(`${today}T00:00:00Z`) + days * 86_400_000).toISOString().slice(0, 10);
const us = (iso: string) => { const [y, m, d] = iso.split("-").map(Number); return `${m}/${d}/${y}`; };

const notice = (o: { entered: string; hearing: string; due: string; to?: string; from?: string; preface?: string; docket?: string }) => [
  `From: ${o.from ?? "cmecf_notice@utd.uscourts.gov"}`, `To: ${o.to ?? "Jane Smith <jane@firm.example>"}`,
  "Subject: Activity in Case 2:26-cv-00123-DBB Smith v. Acme Corporation Order on Motion to Dismiss",
  "Date: Mon, 02 Nov 2026 15:14:00 -0700", "MIME-Version: 1.0", "Content-Type: text/plain; charset=utf-8", "",
  ...(o.preface ? [o.preface, ""] : []),
  "This is an automatic e-mail message generated by the CM/ECF system. Please DO NOT RESPOND to this e-mail because the mail box is unattended.",
  "", "U.S. District Court", "", "District of Utah", "", "Notice of Electronic Filing", "",
  `The following transaction was entered on ${us(o.entered)} at 3:14 PM MST and filed on ${us(o.entered)}`,
  "Case Name: Smith v. Acme Corporation", "Case Number: 2:26-cv-00123-DBB", "Filer:", "Document Number: 12", "",
  "Docket Text:",
  o.docket ?? `ORDER granting in part [10] Motion to Dismiss. Motion Hearing set for ${us(o.hearing)} at 10:00 AM in Room 7.100 before Judge David Barlow. Responses due by ${us(o.due)}. Signed by Judge David Barlow. (jds)`,
  "", "", "2:26-cv-00123-DBB Notice has been electronically mailed to:", "Jane Smith  jane@firm.example", "",
  "https://ecf.utd.uscourts.gov/doc1/18315123456?caseid=139421&de_seq_num=55&magic_num=12345", "",
].join("\r\n");

async function setup() {
  const f = await newFirm(db);
  const x = await db.withFirm(f.owner, async (s) => {
    const client = await createClient(s, { kind: "person", displayName: "Pat Smith", email: "pat.smith@example.com" });
    const para = await inviteUser(s, { email: `p@${f.slug}.example`, fullName: "Pat Para", role: "paralegal", locationId: f.locationId });
    const matter = await createMatter(s, { title: "Smith v. Acme", clientId: client.id, leadAttorneyId: f.ownerUserId, jurisdictionState: "UT" });
    await setCourtCaseNumber(s, matter.id, "2:26-cv-00123");
    return { para, matter };
  });
  return { ...f, ...x, paraCtx: { firmId: f.firmId, userId: x.para.id } as RequestContext };
}

/** RFC 5545 unfolding: CRLF followed by one space or tab joins lines. */
const unfold = (ics: string) => ics.replace(/\r\n[ \t]/g, "");

describe("security review 17", () => {
  // F1 — regex denial of service in the court-name pattern (src/court/nef.ts, parseNef `court`).
  it("F1: parseNef stays fast on a notice with a long whitespace run after 'U.S. District Court'", () => {
    const crlf = `Notice of Electronic Filing\nU.S. District Court${"\r\n".repeat(22)}X`;
    let started = Date.now();
    parseNef(crlf);
    const crlfMs = Date.now() - started;
    const spaces = `Notice of Electronic Filing\nU.S. District Court${" ".repeat(500)}X`;
    started = Date.now();
    parseNef(spaces);
    const spacesMs = Date.now() - started;
    // A notice of a few hundred bytes must not take seconds (a 30-line run takes hours; the input limit is 200,000 characters).
    expect({ crlfMs: crlfMs < 300, spacesMs: spacesMs < 300 }).toEqual({ crlfMs: true, spacesMs: true });
  });

  it("F1 (end to end): one crafted email filed into a Matter makes every view of its court page block the server", async () => {
    const x = await setup();
    const crafted = [
      "From: someone@example.com", "To: jane@firm.example", "Subject: FYI", "MIME-Version: 1.0", "Content-Type: text/plain", "",
      "Notice of Electronic Filing", "CM/ECF", `U.S. District Court${" ".repeat(450)}X`, "",
    ].join("\r\n");
    await upload(x.owner, x.matter.id, "crafted.eml", crafted);
    await process();
    const started = Date.now();
    await db.withFirm(x.paraCtx, (s) => courtNotices(s, x.matter.id));
    expect(Date.now() - started).toBeLessThan(500);
  });

  // F2 — JavaScript (UTF-16) offsets are used as database (code point) positions in worker_save_court_suggestions.
  it("F2: a proposal's quote is the exact words its date was read from, even after an emoji earlier in the email", async () => {
    const x = await setup();
    const text = notice({ entered: plus(-3), hearing: plus(7), due: plus(14), preface: "FYI see below 👍👍👍👍👍👍👍👍 — Jane" });
    await upload(x.owner, x.matter.id, "fwd-nef.eml", text);
    await process();
    const events = await db.withFirm(x.paraCtx, (s) => listCourtEvents(s, x.matter.id));
    const due = events.find((e) => e.title === "Responses due");
    expect(due).toBeTruthy();
    expect(due!.quote).toBe(`Responses due by ${us(plus(14))}`);
  });

  // F3 — the same notice delivered to two attorneys of the firm is proposed twice; a rejection doesn't hold.
  it("F3: a rejected date is not proposed again when the same court notice arrives in a second attorney's mailbox", async () => {
    const x = await setup();
    await upload(x.owner, x.matter.id, "nef-jane.eml", notice({ entered: plus(-3), hearing: plus(7), due: plus(14) }));
    await process();
    for (const e of await db.withFirm(x.owner, (s) => listCourtEvents(s, x.matter.id))) {
      await db.withFirm(x.owner, (s) => decideCourtEvent(s, e.id, "rejected"));
    }
    // CM/ECF sends one copy per attorney of record; only the To: line differs.
    await upload(x.owner, x.matter.id, "nef-bob.eml", notice({ entered: plus(-3), hearing: plus(7), due: plus(14), to: "Bob Lee <bob@firm.example>" }));
    await process();
    const proposed = (await db.withFirm(x.owner, (s) => listCourtEvents(s, x.matter.id))).filter((e) => e.status === "suggested");
    expect(proposed.map((e) => e.title)).toEqual([]);
    // And the docket lists the one filing once.
    expect(await db.withFirm(x.owner, (s) => courtNotices(s, x.matter.id))).toHaveLength(1);
  });

  // F4 — a deadline that the order vacates is proposed, and its quote stops before "VACATED".
  it("F4: a deadline the docket text vacates is not proposed (as already done for 'set for … is VACATED')", () => {
    const n = parseNef(notice({
      entered: plus(-1), hearing: plus(7), due: plus(14),
      docket: `ORDER. The Motion Hearing set for ${us(plus(7))} at 10:00 AM is VACATED. The Dispositive motions deadline ${us(plus(30))} is VACATED. Responses due by ${us(plus(14))} are STRICKEN. Signed by Judge David Barlow.`,
    }))!;
    expect(n.events.map((e) => [e.title, e.date])).toEqual([]);
  });

  // F5 — calendar file folding splits emoji (UTF-16 surrogate pairs) in half.
  it("F5: folding long calendar lines never cuts a character in half", async () => {
    const x = await setup();
    const title = `abc${"😀".repeat(30)}`;
    await db.withFirm(x.owner, (s) => addCourtEvent(s, x.matter.id, { kind: "hearing", title, date: plus(5) }));
    const { body } = await db.withFirm(x.owner, (s) => courtCalendarIcs(s, x.matter.id, true));
    // As a calendar program reads it: UTF-8 bytes, unfolded.
    const read = unfold(Buffer.from(body, "utf8").toString("utf8"));
    expect(read).not.toContain("�");
    expect(read).toContain(`SUMMARY:Hearing: ${title} (`);
  });

  // F6 — timed events reference a TZID with no VTIMEZONE (RFC 5545 §3.2.19 requires one per TZID).
  it("F6: a calendar file using TZID defines that time zone (VTIMEZONE)", async () => {
    const x = await setup();
    await db.withFirm(x.owner, (s) => addCourtEvent(s, x.matter.id, { kind: "hearing", title: "Motion Hearing", date: plus(5), time: "10:00" }));
    const { body } = await db.withFirm(x.owner, (s) => courtCalendarIcs(s, x.matter.id, true));
    expect(body).toContain("DTSTART;TZID=America/Denver:");
    expect(body).toMatch(/BEGIN:VTIMEZONE\r\nTZID:America\/Denver/);
  });

  // F7 — the free-look count depends on the server process's time zone (pg returns `date` as local midnight).
  it("F7: free-look days left don't depend on the server's time zone", async () => {
    const x = await setup();
    await upload(x.owner, x.matter.id, "nef.eml", notice({ entered: plus(-3), hearing: plus(7), due: plus(14) }));
    await process();
    const saved = globalThis.process.env.TZ;
    try {
      globalThis.process.env.TZ = "Pacific/Auckland";
      const [n] = await db.withFirm(x.paraCtx, (s) => courtNotices(s, x.matter.id));
      expect(n!.freeLookDaysLeft).toBe(12);
    } finally {
      if (saved === undefined) delete globalThis.process.env.TZ; else globalThis.process.env.TZ = saved;
    }
  });

  // F8 — a decision or "done" that changes nothing still rewrites who/when (done) and writes audit entries.
  it("F8: marking an already-done date done again keeps who marked it and when", async () => {
    const x = await setup();
    const id = await db.withFirm(x.owner, (s) => addCourtEvent(s, x.matter.id, { kind: "deadline", title: "Expert disclosures", date: plus(3) }));
    await db.withFirm(x.paraCtx, (s) => setCourtEventDone(s, id, true));
    const before = (await t.admin.query("SELECT done_by, done_at FROM huis.court_events WHERE id = $1", [id])).rows[0];
    await db.withFirm(x.owner, (s) => setCourtEventDone(s, id, true));
    const after = (await t.admin.query("SELECT done_by, done_at FROM huis.court_events WHERE id = $1", [id])).rows[0];
    expect(after.done_by).toBe(x.para.id);
    expect(after.done_at).toEqual(before.done_at);
  });

  it("F8b: confirming an already-confirmed date writes no 'confirmed' audit entry (nothing was decided)", async () => {
    const x = await setup();
    const id = await db.withFirm(x.owner, (s) => addCourtEvent(s, x.matter.id, { kind: "deadline", title: "Expert disclosures", date: plus(3) }));
    await db.withFirm(x.owner, (s) => decideCourtEvent(s, id, "confirmed"));
    const row = (await t.admin.query("SELECT decided_by FROM huis.court_events WHERE id = $1", [id])).rows[0];
    expect(row.decided_by).toBeNull(); // the database agrees nothing was decided
    const audits = await t.admin.query("SELECT count(*)::int AS n FROM huis.audit_events WHERE firm_id = $1 AND action = 'court.confirmed'", [x.firmId]);
    expect(audits.rows[0].n).toBe(0);
  });

  // F9 — anyone can plant "court notice" proposals and docket entries with an ordinary email (no check of who sent it).
  it("F9: an email that merely contains NEF wording, from an outside sender, is not treated as a federal court notice", async () => {
    const x = await setup();
    await upload(x.owner, x.matter.id, "fake.eml", notice({
      entered: plus(-1), hearing: plus(2), due: plus(4), from: "Opposing Counsel <mallory@evil.example>",
    }));
    await process();
    expect((await db.withFirm(x.owner, (s) => listCourtEvents(s, x.matter.id))).filter((e) => e.origin === "huis")).toEqual([]);
    expect(await db.withFirm(x.owner, (s) => courtNotices(s, x.matter.id))).toEqual([]);
  });
});
